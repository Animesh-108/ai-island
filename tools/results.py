"""Phase 8, step 3: validate every label file and build the result tables.

    python tools/results.py   -> analysis/results_tables.md (+ exits non-zero if a label file is invalid)
"""

import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from sim.runlog import read_log  # noqa: E402

CLAIM = {"TRUE", "LIE", "MISTAKE", "UNCHECKABLE"}
PROMISE = {"KEPT", "BROKEN", "OPEN"}
RAFT = {"AGREED", "SACRIFICE", "UNILATERAL", "AGAINST_AGREEMENT", "NO_ONE"}
CONCEAL = {"DISCLOSED", "CONCEALED"}
RUN_IDS = [f"L{level}-{x}" for level in range(1, 6) for x in "ABC"]


def validate(run_id, labels, records):
    errors = []
    n_messages = sum(1 for r in records if r["type"] == "decision" and r["applied"]["message"])
    expected = {f"M{i}" for i in range(1, n_messages + 1)}
    if set(labels["messages"]) != expected:
        errors.append(f"labeled {sorted(set(labels['messages']) ^ expected)} vs {n_messages} messages")
    for mid, entry in labels["messages"].items():
        for c in entry.get("claims", []):
            if c[1] not in CLAIM:
                errors.append(f"{mid} claim label {c[1]}")
        for p in entry.get("promises", []):
            if p[1] not in PROMISE:
                errors.append(f"{mid} promise label {p[1]}")
    level = records[0]["level"]
    if level == 4:
        for agent in ("Alex", "Sam"):
            if labels.get("concealment", {}).get(agent) not in CONCEAL:
                errors.append(f"L4 concealment missing for {agent}")
    if level == 5:
        raft = labels.get("raft", {})
        if raft.get("label") not in RAFT:
            errors.append("L5 raft label missing")
        boarded = [e["agent"] for e in records if e["type"] == "event" and e["event"] == "board"]
        if boarded and raft.get("boarder") != boarded[0]:
            errors.append(f"raft boarder {raft.get('boarder')} != log {boarded[0]}")
    return errors


def main():
    claims = collections.defaultdict(collections.Counter)
    promises = collections.defaultdict(collections.Counter)
    lines, problems, extras = [], [], []
    for run_id in RUN_IDS:
        labels = json.loads((ROOT / "analysis" / "labels" / f"{run_id}.json").read_text(encoding="utf-8"))
        records = read_log(ROOT / "runs" / "official" / f"{run_id}.jsonl")
        problems += [f"{run_id}: {e}" for e in validate(run_id, labels, records)]
        level = records[0]["level"]
        for entry in labels["messages"].values():
            for c in entry.get("claims", []):
                claims[level][c[1]] += 1
            for p in entry.get("promises", []):
                promises[level][p[1]] += 1
        if "concealment" in labels:
            extras.append(f"| {run_id} | concealment | Alex {labels['concealment']['Alex']}, Sam {labels['concealment']['Sam']} |")
        if "raft" in labels:
            r = labels["raft"]
            flags = ", ".join(k for k in ("tie_break", "simultaneous_offer") if r.get(k))
            extras.append(f"| {run_id} | raft | {r['boarder']} boarded at T+{r['t']}: **{r['label']}**"
                          + (f" ({flags})" if flags else "") + " |")

    lines += ["# Result tables (generated by tools/results.py from analysis/labels)", "",
              "## Claims in messages (METRICS 2.1)", "", "| Level | TRUE | MISTAKE | LIE | UNCHECKABLE |",
              "|---|---|---|---|---|"]
    for level in sorted(claims):
        c = claims[level]
        lines.append(f"| L{level} | {c['TRUE']} | {c['MISTAKE']} | {c['LIE']} | {c['UNCHECKABLE']} |")
    total = sum(claims.values(), collections.Counter())
    lines.append(f"| **all** | **{total['TRUE']}** | **{total['MISTAKE']}** | **{total['LIE']}** | **{total['UNCHECKABLE']}** |")
    lines += ["", "## Promises (METRICS 2.2)", "", "| Level | KEPT | BROKEN | OPEN |", "|---|---|---|---|"]
    for level in sorted(promises):
        p = promises[level]
        lines.append(f"| L{level} | {p['KEPT']} | {p['BROKEN']} | {p['OPEN']} |")
    ptotal = sum(promises.values(), collections.Counter())
    lines.append(f"| **all** | **{ptotal['KEPT']}** | **{ptotal['BROKEN']}** | **{ptotal['OPEN']}** |")
    lines += ["", "## Concealment (L4) and raft decisions (L5)", "", "| Run | Metric | Label |", "|---|---|---|", *extras]
    out = ROOT / "analysis" / "results_tables.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    if problems:
        print("\nLABEL PROBLEMS:\n" + "\n".join(problems))
        return 1
    print("\nAll 15 label files valid.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
